#!/usr/bin/env python3
"""
train_sr_model.py
=================
Trains the ESRGAN model on the paired LR/HR dataset generated by generate_sr_dataset.py.
"""

import os
import sys
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import Dataset, DataLoader
from pathlib import Path
from tqdm import tqdm

# Add project root to sys.path
sys.path.insert(0, str(Path(__file__).parent.parent))

from models.esrgan import build_esrgan

class SRDataset(Dataset):
    def __init__(self, data_dir):
        self.lr_dir = Path(data_dir) / 'LR'
        self.hr_dir = Path(data_dir) / 'HR'
        self.samples = sorted(list(self.lr_dir.glob('*.pt')))
        
    def __len__(self):
        return len(self.samples)
    
    def __getitem__(self, idx):
        lr_path = self.samples[idx]
        hr_path = self.hr_dir / lr_path.name
        
        lr_tensor = torch.load(lr_path, weights_only=True)
        hr_tensor = torch.load(hr_path, weights_only=True)
        return lr_tensor, hr_tensor

def train_sr(data_dir='dataset_sr', epochs=50, batch_size=1, lr=1e-4, save_dir='runs/esrgan', device='cpu'):
    print(f"Training on device: {device}")
    
    Path(save_dir).mkdir(parents=True, exist_ok=True)
    
    dataset = SRDataset(data_dir)
    if len(dataset) == 0:
        raise ValueError(f"No data found in {data_dir}. Run generate_sr_dataset.py first.")
        
    # Split into train/val
    train_size = int(0.8 * len(dataset))
    val_size = len(dataset) - train_size
    train_dataset, val_dataset = torch.utils.data.random_split(dataset, [train_size, val_size])
    
    train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
    val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False)
    
    model = build_esrgan(in_channels=3, out_channels=3).to(device)
    criterion = nn.L1Loss() # Standard L1 Loss for Pixel-SR
    optimizer = optim.Adam(model.parameters(), lr=lr)
    
    best_val_loss = float('inf')
    
    for epoch in range(epochs):
        model.train()
        train_loss = 0.0
        for lr_batch, hr_batch in tqdm(train_loader, desc=f"Epoch {epoch+1}/{epochs}"):
            lr_batch = lr_batch.to(device)
            hr_batch = hr_batch.to(device)
            
            optimizer.zero_grad()
            sr_batch = model(lr_batch)
            loss = criterion(sr_batch, hr_batch)
            loss.backward()
            optimizer.step()
            
            train_loss += loss.item() * lr_batch.size(0)
            
        train_loss /= len(train_dataset)
        
        model.eval()
        val_loss = 0.0
        with torch.no_grad():
            for lr_batch, hr_batch in val_loader:
                lr_batch = lr_batch.to(device)
                hr_batch = hr_batch.to(device)
                sr_batch = model(lr_batch)
                loss = criterion(sr_batch, hr_batch)
                val_loss += loss.item() * lr_batch.size(0)
        val_loss /= len(val_dataset)
        
        print(f"Epoch {epoch+1:03d} | Train Loss: {train_loss:.6f} | Val Loss: {val_loss:.6f}")
        
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            torch.save(model.state_dict(), Path(save_dir) / 'best.pt')
            print("  --> Saved new best model")
            
    print("Training complete!")

if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('--device', type=str, default='cpu', help='Device to use for training (cpu or cuda)')
    args = parser.parse_args()
    
    train_sr(device=args.device)
